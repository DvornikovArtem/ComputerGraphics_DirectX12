inline float saturate(float x)
{
    return (std::min)((std::max)(x, 0.0f), 1.0f);
}

inline float lerp(float a, float b, float t)
{
    return a + (b - a) * t;
}

inline float smoothstep(float a, float b, float x)
{
    float t = saturate((x - a) / (b - a + 1e-6f));
    return t * t * (3.0f - 2.0f * t);
}


DensityFieldCPU VoxelWorld::GenerateDensityCPU(const Chunk& c)
{
    const VoxelChunkCB& info = c.cb;

    DensityFieldCPU df;
    df.dimX = info.dimX; df.dimY = info.dimY; df.dimZ = info.dimZ;
    df.data.resize(size_t(df.dimX) * df.dimY * df.dimZ);

    NoiseSettings ns_height;
    ns_height.frequency = 0.015f;
    ns_height.octaves = 5;
    ns_height.lacunarity = 2.0f;
    ns_height.gain = 0.5f;
    ns_height.amplitude = 1.0f;

    NoiseSettings ns_caves;
    ns_caves.frequency = 0.08f;
    ns_caves.octaves = 3;
    ns_caves.lacunarity = 2.0f;
    ns_caves.gain = 0.5f;
    ns_caves.amplitude = 1.0f;

    const float seaLevelY = 0.0f;
    const float heightScale = 50.0f;
    const float bedrockY = 0.0f;
    const float bedrockFade = 12.0f;

    int   countAbove = 0, countBelow = 0;
    float minDensity = FLT_MAX, maxDensity = -FLT_MAX;

    for (UINT z = 0; z < df.dimZ; ++z)
        for (UINT y = 0; y < df.dimY; ++y)
            for (UINT x = 0; x < df.dimX; ++x)
            {
                const UINT idx = x + y * df.dimX + z * df.dimX * df.dimY;

                DirectX::XMFLOAT3 wp = {
                    info.worldOrigin.x + x * info.voxelSize,
                    info.worldOrigin.y + y * info.voxelSize,
                    info.worldOrigin.z + z * info.voxelSize
                };

                float h = FBM3D({ wp.x, 0.0f, wp.z }, ns_height);
                float surfaceY = seaLevelY + h * heightScale;

                float densityTerrain = (wp.y - surfaceY);

                float caveFBM = FBM3D(wp, ns_caves);
                const float caveThr = 0.82f;
                float densityCaves = caveFBM - caveThr;
                float cavesFadeTopStart = surfaceY - 6.0f;
                float cavesFadeT = saturate((wp.y - bedrockY) / (cavesFadeTopStart - bedrockY + 1e-4f));
                densityCaves = lerp(-1.0f, densityCaves, cavesFadeT);

                if (wp.y < bedrockY) {
                    densityTerrain = (std::min)(densityTerrain, -5.0f);
                }
                else if (wp.y < bedrockY + bedrockFade) {
                    float t = saturate((wp.y - bedrockY) / bedrockFade);
                    densityTerrain = lerp(-5.0f, densityTerrain, t);
                }

                float density = (std::max)(densityTerrain, densityCaves);

                bool isExtXNeg = c.isExternalBoundary[0] && (x == 0);
                bool isExtXPos = c.isExternalBoundary[1] && (x == df.dimX - 1);
                bool isExtZNeg = c.isExternalBoundary[2] && (z == 0);
                bool isExtZPos = c.isExternalBoundary[3] && (z == df.dimZ - 1);
                bool isBottom = (y == 0);

                if (isExtXNeg || isExtXPos || isExtZNeg || isExtZPos || isBottom)
                {
                    density = (std::max)(density, 1.0f);
                }


                df.data[idx] = DirectX::PackedVector::XMConvertFloatToHalf(density);

                if (density > info.isoLevel) ++countAbove; else ++countBelow;
                minDensity = (std::min)(minDensity, density);
                maxDensity = (std::max)(maxDensity, density);
            }

    char buf[256];
    sprintf_s(buf, "Density: min=%.2f, max=%.2f, iso=%.2f, above=%d, below=%d\n",
        minDensity, maxDensity, info.isoLevel, countAbove, countBelow);
    OutputDebugStringA(buf);

    if (info.isoLevel < minDensity || info.isoLevel > maxDensity)
        OutputDebugStringA("WARNING: isoLevel outside density range!\n");

    return df;
}

void VoxelWorld::UploadDensity3D(ID3D12GraphicsCommandList* cmd, Chunk& c, const DensityFieldCPU& df)
{
    bool createdNow = false;

    if (!c.gpu.densityTex) {
        D3D12_RESOURCE_DESC desc = {};
        desc.Dimension = D3D12_RESOURCE_DIMENSION_TEXTURE3D;
        desc.Width = df.dimX;
        desc.Height = df.dimY;
        desc.DepthOrArraySize = (UINT16)df.dimZ;
        desc.MipLevels = 1;
        desc.Format = DXGI_FORMAT_R16_FLOAT;
        desc.SampleDesc = { 1,0 };
        desc.Layout = D3D12_TEXTURE_LAYOUT_UNKNOWN;
        desc.Flags = D3D12_RESOURCE_FLAG_NONE;

        ThrowIfFailed(mDevice->CreateCommittedResource(
            &CD3DX12_HEAP_PROPERTIES(D3D12_HEAP_TYPE_DEFAULT),
            D3D12_HEAP_FLAG_NONE,
            &desc,
            D3D12_RESOURCE_STATE_COPY_DEST,
            nullptr,
            IID_PPV_ARGS(&c.gpu.densityTex)));

        createdNow = true;
    }

    const UINT64 uploadSz = GetRequiredIntermediateSize(c.gpu.densityTex.Get(), 0, 1);
    if (!c.gpu.densityUpload || c.gpu.densityUpload->GetDesc().Width < uploadSz)
    {
        ThrowIfFailed(mDevice->CreateCommittedResource(
            &CD3DX12_HEAP_PROPERTIES(D3D12_HEAP_TYPE_UPLOAD),
            D3D12_HEAP_FLAG_NONE,
            &CD3DX12_RESOURCE_DESC::Buffer(uploadSz),
            D3D12_RESOURCE_STATE_GENERIC_READ,
            nullptr,
            IID_PPV_ARGS(c.gpu.densityUpload.ReleaseAndGetAddressOf())));
    }

    if (!createdNow)
    {
        auto toCopy = CD3DX12_RESOURCE_BARRIER::Transition(
            c.gpu.densityTex.Get(),
            D3D12_RESOURCE_STATE_NON_PIXEL_SHADER_RESOURCE,
            D3D12_RESOURCE_STATE_COPY_DEST);
        cmd->ResourceBarrier(1, &toCopy);
    }

    D3D12_SUBRESOURCE_DATA s = {};
    s.pData = df.data.data();
    s.RowPitch = size_t(df.dimX) * sizeof(uint16_t);
    s.SlicePitch = size_t(df.dimX) * df.dimY * sizeof(uint16_t);

    UpdateSubresources(cmd, c.gpu.densityTex.Get(), c.gpu.densityUpload.Get(), 0, 0, 1, &s);

    auto toRead = CD3DX12_RESOURCE_BARRIER::Transition(
        c.gpu.densityTex.Get(),
        D3D12_RESOURCE_STATE_COPY_DEST,
        D3D12_RESOURCE_STATE_NON_PIXEL_SHADER_RESOURCE);
    cmd->ResourceBarrier(1, &toRead);
}

